"""Aggregate all results -> results/SUMMARY.md + figures in results/fig/."""
import glob
import json
import os
from collections import defaultdict

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from hastabench.hastas import CORE8, ALL28

R = "results"
os.makedirs(f"{R}/fig", exist_ok=True)
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
CAT = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
plt.rcParams.update({"font.size": 9, "axes.edgecolor": INK2, "axes.labelcolor": INK2, "xtick.color": INK2,
                     "ytick.color": INK2, "axes.spines.top": False, "axes.spines.right": False,
                     "figure.facecolor": SURF, "axes.facecolor": SURF})
PRICE = {  # $/M tokens (input, output), approximate list prices
    "azure/gpt-5-mini": (0.25, 2.0), "gcp/gemini-3.8-flash": (0.3, 2.5), "claude-haiku-4-5": (1.0, 5.0),
    "claude-sonnet-5-5": (3.0, 15.0)}


def load_jsonl(p):
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []


def agg(rows, names=None):
    rows = [r for r in rows if names is None or r["target"] in names]
    if not rows:
        return None
    s = [r["score"] for r in rows]
    return dict(n=len(rows), success=np.mean([x["success"] for x in s]), hs=np.mean([x["hasta_score"] for x in s]),
                kp=np.mean([x["kp_err_mm"] for x in s]), orient=np.mean([x.get("orient_err_deg", x.get("rel_rot_err_deg", 0)) for x in s]),
                cons=np.mean([x.get("constraint_frac", np.mean(x.get("cross_contacts_ok", [1]) or [1])) for x in s]))


def fmt(a, keys=("n", "success", "hs", "kp", "orient", "cons")):
    if a is None:
        return "| – " * len(keys)
    out = []
    for k in keys:
        v = a[k]
        out.append(f"{v:d}" if k == "n" else f"{100 * v:.1f}%" if k in ("success", "cons") else f"{v:.3f}" if k == "hs" else f"{v:.1f}")
    return "| " + " | ".join(out)


md = ["# HastaBench v1 — results summary", "",
      "Auto-generated by `scripts/summarize.py`. Success = hidden final-state scorer (all keypoints, per-finger, orientation, contacts, validity).", ""]

# ---------------------------------------------------------------- single hand
methods = {}
for p in sorted(glob.glob(f"{R}/baselines/*_all28.jsonl")):
    rows = load_jsonl(p)
    if rows:
        methods[os.path.basename(p).replace("_all28.jsonl", "")] = rows
import re
vlm = {}
for p in sorted(glob.glob(f"{R}/vlm/*.jsonl")):
    rows = load_jsonl(p)
    if not rows or "samyuta" in p:
        continue
    key = re.sub(r"_s\d+$", "", os.path.basename(p).replace(".jsonl", ""))
    d = vlm.setdefault(key, {})
    for r in rows:
        d.setdefault((r["target"], r["seed"]), r)      # dedupe (target, seed)
vlm = {k: list(v.values()) for k, v in vlm.items()}
rl = {}
for d in sorted(glob.glob(f"{R}/rl/*/")):
    if os.path.exists(d + "eval_nominal.json"):
        rows = json.load(open(d + "eval_nominal.json"))
        rl["rl_" + os.path.basename(d.rstrip("/"))] = [dict(target=r["target"], seed=r["seed"], score=r) for r in rows]

md += ["## 1. Single-hand benchmark (28 asamyuta hastas)", "",
       "| method | track | episodes | success | HastaScore | kp err (mm) | orient err (°) | constraints | core-8 success | tokens/ep | ≈$ total |",
       "|---|---|---|---|---|---|---|---|---|---|---|"]
table_rows = []
for name, rows in list(methods.items()) + list(vlm.items()) + list(rl.items()):
    track = ("privileged-state" if "ik_oracle" in name or "rl_state" in name else "image-only")
    if name.startswith(("noop",)):
        track = "–"
    a, c8 = agg(rows), agg(rows, CORE8)
    tok, cost = "–", "–"
    if name in vlm:
        pt = np.mean([r["usage"]["prompt"] for r in rows]); ct = np.mean([r["usage"]["completion"] for r in rows])
        tok = f"{pt / 1000:.0f}k+{ct / 1000:.1f}k"
        m = rows[0]["model"]
        if m in PRICE:
            cost = f"{sum(r['usage']['prompt'] * PRICE[m][0] + r['usage']['completion'] * PRICE[m][1] for r in rows) / 1e6:.2f}"
        track = "VLM image-only" + (" +name hint" if "hint" in name else "")
    md.append(f"| {name} | {track} {fmt(a)[0:]} | {100 * c8['success']:.1f}% | {tok} | {cost} |".replace("|  |", "|"))
    table_rows.append((name, a))
md.append("")
md.append("Budgets: VLMs 40 tool calls (each set_joint / rotate / render = 1); `*_bN` = N simulator actions; RL = 10 full-vector actions. "
          "Initial poses are the same seeded configurations for every method (seeds 0,1,2; Haiku 0,1; Sonnet core-8 0,1).")
md.append("")

# figure 1: success per method (single hue) + figure 2: hasta score
if table_rows:
    order = sorted(table_rows, key=lambda t: t[1]["success"])
    fig, axes = plt.subplots(1, 2, figsize=(10, 0.32 * len(order) + 1.2))
    for ax, key, lab in zip(axes, ["success", "hs"], ["success rate (28 hastas)", "mean HastaScore (0–1)"]):
        vals = [t[1][key] for t in order]
        ax.barh(range(len(order)), vals, color=CAT[0], height=0.6)
        ax.set_yticks(range(len(order)))
        ax.set_yticklabels([t[0] for t in order] if ax is axes[0] else [""] * len(order))
        ax.set_xlim(0, 1)
        ax.grid(axis="x", color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        ax.set_title(lab, color=INK, loc="left", fontsize=10)
        for i, v in enumerate(vals):
            ax.text(v + 0.01, i, f"{v:.2f}", va="center", color=INK2, fontsize=8)
    plt.tight_layout()
    plt.savefig(f"{R}/fig/single_hand_methods.png", dpi=150)
    plt.close()

    # figure 2: per-hasta heatmap of success rate
    names = [t[0] for t in order][::-1]
    allrows = {**methods, **vlm, **rl}
    M = np.zeros((len(names), len(ALL28)))
    for i, n in enumerate(names):
        for j, h in enumerate(ALL28):
            rs = [r["score"]["hasta_score"] for r in allrows[n] if r["target"] == h]
            M[i, j] = np.mean(rs) if rs else np.nan
    fig, ax = plt.subplots(figsize=(12, 0.35 * len(names) + 1.8))
    im = ax.imshow(M, cmap="Blues", vmin=0, vmax=1, aspect="auto")
    ax.set_xticks(range(len(ALL28)))
    ax.set_xticklabels([h + ("*" if h in CORE8 else "") for h in ALL28], rotation=60, ha="right")
    ax.set_yticks(range(len(names)))
    ax.set_yticklabels(names)
    ax.spines[:].set_visible(False)
    cb = plt.colorbar(im, ax=ax, fraction=0.02, pad=0.01)
    cb.set_label("mean HastaScore")
    ax.set_title("Per-hasta HastaScore (* = core-8)", color=INK, loc="left")
    plt.tight_layout()
    plt.savefig(f"{R}/fig/per_hasta_heatmap.png", dpi=150)
    plt.close()

# ---------------------------------------------------------------- failure analysis (VLMs)
md += ["## 2. VLM failure analysis", "",
       "Each failed episode is assigned every criterion it violates (so rows can exceed 100%).", "",
       "| model | fail eps | orientation >20° | shape (kp>10mm or a finger >20mm) | contact/apart violated | invalid (penetration) | not submitted (budget) | worst finger (mean max-err mm) |",
       "|---|---|---|---|---|---|---|---|"]
for name, rows in vlm.items():
    fails = [r for r in rows if not r["score"]["success"]]
    if not fails:
        continue
    s = [r["score"] for r in fails]
    o = np.mean([x["orient_err_deg"] > 20 for x in s])
    sh = np.mean([x["kp_err_mm"] > 10 or max(x["finger_err_mm"].values()) > 20 for x in s])
    co = np.mean([x["constraint_frac"] < 1 for x in s])
    inv = np.mean([not x["valid"] for x in s])
    ns = np.mean([not r["submitted"] for r in fails])
    fe = defaultdict(list)
    for x in s:
        for f, v in x["finger_err_mm"].items():
            fe[f].append(v)
    worst = sorted(((np.mean(v), f) for f, v in fe.items()), reverse=True)
    md.append(f"| {name} | {len(fails)}/{len(rows)} | {100 * o:.0f}% | {100 * sh:.0f}% | {100 * co:.0f}% | {100 * inv:.0f}% | {100 * ns:.0f}% | "
              + ", ".join(f"{f} {v:.0f}" for v, f in worst[:3]) + " |")
md.append("")

# VLM vs RL on identical (target, seed)
if vlm and rl:
    md += ["## 3. Does RL succeed where VLMs fail? (same target, same start configuration)", "",
           "| VLM | RL policy | VLM fails | ...of which RL succeeds |", "|---|---|---|---|"]
    for vn, vrows in vlm.items():
        for rn, rrows in rl.items():
            rs = {(r["target"], r["seed"]): r["score"]["success"] for r in rrows}
            vf = [(r["target"], r["seed"]) for r in vrows if not r["score"]["success"] and (r["target"], r["seed"]) in rs]
            if vf:
                md.append(f"| {vn} | {rn} | {len(vf)} | {sum(rs[k] for k in vf)} ({100 * np.mean([rs[k] for k in vf]):.0f}%) |")
    md.append("")

# ---------------------------------------------------------------- RL details
md += ["## 4. RL environment results", ""]
curves = {}
for d in sorted(glob.glob(f"{R}/rl/*/")):
    n = os.path.basename(d.rstrip("/"))
    if os.path.exists(d + "final.json"):
        f = json.load(open(d + "final.json"))
        md.append(f"- **{n}** ({f['args']['obs']} obs, train on {f['args']['train']}"
                  + (", randomized hands" if f['args'].get('randomize_hand') else "") + f", {f['args']['steps'] / 1e6:.0f}M steps, {f['train_minutes']:.0f} min): "
                  f"28-hasta success {100 * f['nominal']['success']:.1f}% (core-8 {100 * f['nominal']['core8_success']:.1f}%), HastaScore {f['nominal']['hasta_score']:.3f}, "
                  f"kp {f['nominal']['kp_err_mm']:.1f} mm; held-out hand proportions success {100 * f['heldout_proportions_mean_success']:.1f}%")
    elif os.path.exists(d + "curve.json"):
        md.append(f"- **{n}**: still training / incomplete; last eval " + json.dumps(json.load(open(d + "curve.json"))[-1]))
    if os.path.exists(d + "curve.json"):
        curves[n] = json.load(open(d + "curve.json"))
md.append("")
if curves:
    fig, ax = plt.subplots(figsize=(6.5, 3.6))
    for i, (n, c) in enumerate(curves.items()):
        x = [e["steps"] / 1e6 for e in c]
        y = [e["success"] for e in c]
        ax.plot(x, y, color=CAT[i], lw=2, marker="o", ms=4, label=n)
        ax.text(x[-1] + 0.1, y[-1], n, color=INK2, fontsize=8, va="center")
    ax.set_xlabel("environment steps (M)")
    ax.set_ylabel("success on 28 hastas (seed 0)")
    ax.set_ylim(-0.02, 1.02)
    ax.grid(color=GRID, lw=0.8)
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    ax.set_title("RL learning curves", color=INK, loc="left")
    plt.tight_layout()
    plt.savefig(f"{R}/fig/rl_curves.png", dpi=150)
    plt.close()

# ---------------------------------------------------------------- two hands
md += ["## 5. Two-hand (samyuta) tasks", "",
       "| method | episodes | success | score | rel. rot err (°) | rel. pos err (mm) | cross-contacts ok |", "|---|---|---|---|---|---|---|"]
two = {}
for p in sorted(glob.glob(f"{R}/baselines/*_samyuta.jsonl")) + sorted(glob.glob(f"{R}/vlm/*samyuta*.jsonl")):
    rows = load_jsonl(p)
    if rows:
        two[os.path.basename(p).replace(".jsonl", "")] = rows
for n, rows in two.items():
    s = [r["score"] for r in rows]
    md.append(f"| {n} | {len(rows)} | {100 * np.mean([x['success'] for x in s]):.0f}% | {np.mean([x['hasta_score'] for x in s]):.3f} | "
              f"{np.mean([x['rel_rot_err_deg'] for x in s]):.1f} | {np.mean([x['rel_pos_err_mm'] for x in s]):.1f} | "
              f"{100 * np.mean([np.mean(x['cross_contacts_ok']) if x['cross_contacts_ok'] else 1 for x in s]):.0f}% |")
md.append("")

if os.path.exists(f"{R}/scorer_validation.json"):
    v = json.load(open(f"{R}/scorer_validation.json"))
    md += ["## 6. Scorer reliability", "",
           f"- Confusion test: each hasta's shape scored against every other target's: {v['diag_success']}/{v['n']} self-matches succeed, "
           f"{v['offdiag_false_success']} of {v['n'] * (v['n'] - 1)} cross-matches falsely succeed.",
           "- Robustness: success rate when the true target's joints are perturbed by Gaussian noise: "
           + ", ".join(f"σ={k}: {100 * x:.0f}%" for k, x in v["noise_success"].items()), ""]

md += ["Figures: `results/fig/single_hand_methods.png`, `results/fig/per_hasta_heatmap.png`, `results/fig/rl_curves.png`."]
open(f"{R}/SUMMARY.md", "w").write("\n".join(md) + "\n")
print("\n".join(md))
